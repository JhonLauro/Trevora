/**
 * Every make the picker offers, A to Z.
 *
 * The catalogue's own makes are merged in rather than assumed to be present,
 * so a brand can never be dropped from the picker while its models are still
 * listed — that would leave a model nobody can reach.
 */
export function allMakes() {
  const merged = new Set([...VEHICLE_MAKES, ...Object.keys(VEHICLE_CATALOG)]);
  return [...merged].sort((first, second) => first.localeCompare(second, 'en'));
}
